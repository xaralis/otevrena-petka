"""Generate config/members.yaml from ČSÚ (volby.cz) candidate registries for ZMO Pardubice V.

Inputs are the open-data registries from https://www.volby.cz/opendata/kvRRRR/ :
`kvrk.csv` (candidates, MANDAT=A for elected, PORADINAHR = substitute order) and either
`kvros.csv` (list names) or, for 2026, the results XML (`vysledky_obec`) for list names.

    uv run python scripts/members_from_volby.py \
        --term 2014-2018:2014-10-10:DIR/kv2014/csv_od \
        --term 2018-2022:2018-10-05:DIR/KV2018/csv_od \
        --term 2022-2026:2022-09-23:DIR/KV2022/csv_od \
        --term 2026-2030:2026-10-09:DIR/kv2026 > config/members.yaml

Only lists that won at least one seat are kept – substitutes who later take a seat come
from those lists. The registry is the source of names; the minutes only abbreviate them.
"""

import argparse
import csv
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import yaml

KODZASTUP = "557072"  # Pardubice V


def load_lists(d: Path) -> dict[str, str]:
    ros = d / "kvros.csv"
    if ros.exists():
        with ros.open(encoding="utf-8") as f:
            return {r["POR_STR_HL"]: r["ZKRATKAO30"] or r["NAZEVCELK"]
                    for r in csv.DictReader(f) if r["KODZASTUP"] == KODZASTUP}
    xml = d / "mo5.xml"
    ns = {"v": "http://www.volby.cz/kv/"}
    root = ET.parse(xml).getroot()
    return {e.get("POR_STR_HLAS_LIST"): e.get("NAZEV_STRANY")
            for e in root.iterfind(".//v:VOLEBNI_STRANA", ns)}


def term_entry(spec: str) -> dict:
    term_id, election, path = spec.split(":", 2)
    d = Path(path)
    lists = load_lists(d)
    with (d / "kvrk.csv").open(encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r["KODZASTUP"] == KODZASTUP]
    seats_by_list: dict[str, int] = {}
    for r in rows:
        if r["MANDAT"] == "A":
            seats_by_list[r["POR_STR_HL"]] = seats_by_list.get(r["POR_STR_HL"], 0) + 1
    candidates = []
    for r in sorted(rows, key=lambda r: (int(r["POR_STR_HL"]), int(r["PORCISLO"]))):
        if r["POR_STR_HL"] not in seats_by_list:
            continue
        elected = r["MANDAT"] == "A"
        c = {
            "first": r["JMENO"], "last": r["PRIJMENI"],
            "list": lists.get(r["POR_STR_HL"], r["POR_STR_HL"]),
            "elected": elected,
        }
        if r["TITULPRED"]:
            c["before"] = r["TITULPRED"]
        if r["TITULZA"]:
            c["after"] = r["TITULZA"]
        if not elected and r["PORADINAHR"] not in ("", "0"):
            c["substitute"] = int(r["PORADINAHR"])
        candidates.append(c)
    return {"id": term_id, "election": election,
            "seats": sum(seats_by_list.values()), "candidates": candidates}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--term", action="append", required=True,
                    help="ID:ELECTION_DATE:REGISTRY_DIR")
    args = ap.parse_args()
    doc = {"terms": [term_entry(t) for t in args.term]}
    sys.stdout.write("# Generated by scripts/members_from_volby.py from volby.cz open data.\n"
                     "# Edit only via `aliases` in config/aliases.yaml, not here.\n")
    yaml.safe_dump(doc, sys.stdout, allow_unicode=True, sort_keys=False, width=120)


if __name__ == "__main__":
    main()
